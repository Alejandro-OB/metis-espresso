test('compara perfiles y resalta los parámetros modificados', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'desktop')
  await signIn(page, '/profiles')
  const payload = {
    name: `Perfil comparado ${Date.now()}`,
    coffeeIds: ['coffee-huila-001'],
    specifications: [
      { property: 'water-temperature', unit: '°C', strategy: 'target', target: 93, tolerance: 1 },
      { property: 'pressure', unit: 'bar', strategy: 'range', minimum: 8.5, maximum: 9.5 },
    ],
  }
  const createdResponse = await page.request.post('/api/v1/profiles', { data: payload })
  const created = await createdResponse.json() as { id: string }
  await page.request.post(`/api/v1/profiles/${created.id}/approve`, { data: {} })
  const versionResponse = await page.request.post(`/api/v1/profiles/${created.id}/versions`, { data: { ...payload, name: `${payload.name} refinado`, specifications: [{ ...payload.specifications[0], target: 92.5 }, payload.specifications[1]] } })
  const version = await versionResponse.json() as { id: string }
  await page.reload()
  await page.getByLabel(`Seleccionar ${created.id}`).check()
  await page.getByLabel(`Seleccionar ${version.id}`).check()
  await page.getByRole('button', { name: 'Comparar (2)' }).click()
  await expect(page).toHaveURL(/\/profiles\/compare\?ids=/)
  await expect(page.getByRole('table', { name: 'Resumen de perfiles' })).toContainText('Autor')
  const parameters = page.getByRole('table', { name: 'Parámetros comparados' })
  await expect(parameters).toContainText('Temperatura del agua · Objetivo')
  await expect(parameters).toContainText('Modificado')
  await expect(parameters).toContainText('92.5 °C')
  await expect(page.getByRole('heading', { name: 'Validación y preparaciones relacionadas' })).toBeVisible()
})

